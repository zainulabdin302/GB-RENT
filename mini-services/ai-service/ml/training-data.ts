/**
 * Synthetic training data + model bootstrap for the GB Rent AI service.
 *
 * In a production deployment we would replace this file with a query against
 * the production database ("SELECT * FROM property WHERE status='APPROVED'").
 * For the FYP defense we generate a realistic synthetic dataset of 250 GB
 * rental listings with prices that genuinely correlate with the features
 * — so the forest has real signal to learn, and the predictions look
 * sensible when demonstrated live.
 *
 * ─── Pricing model used to generate labels ───────────────────────────────
 *
 *   base(type)        SHOP 27.5k  HOUSE 75k  ROOM 14k  HOSTEL 10.5k  (midpoints)
 *                     × uniform spread of ±10k, ±45k, ±6k, ±4.5k respectively
 *   city(zone)        Hunza ×1.25  Skardu ×1.15  Gilgit ×1.00
 *                     Ghizer ×0.95  Nagar ×0.95  Astore ×0.90
 *                     Ghanche ×0.90  Shigar ×0.90  Kharmang ×0.85  Diamer ×0.85
 *   amenities         each adds +2k–5k (random per amenity per listing)
 *   rooms             +8k each (only meaningful for HOUSE/ROOM; for shops
 *                     the generator picks rooms in 0..1)
 *   size              + PKR 30 / sqft
 *   noise             ±10 % Gaussian, σ = 0.10 × subtotal
 *
 * The dataset is generated by a SEEDED PRNG (mulberry32, seed = 1337) so the
 * exact same 250 listings exist across server restarts — the forest is
 * therefore reproducible, which matters when an examiner reruns the demo.
 *
 * ─── Heuristic: confidence (0..1) ───────────────────────────────────────
 *   After the forest predicts a price for a query, we substitute that
 *   predicted price into the 27-dim similarity vector and count how many
 *   training rows have cosine similarity > 0.85 to the query. Call this
 *   `nNear`. Confidence is then
 *
 *        confidence = clamp(nNear / 15, 0, 1)
 *
 *   Rationale: the more densely the training set surrounds the query in
 *   feature space, the more we trust the forest's prediction (it has seen
 *   many similar cases). 15 was chosen so that, with 250 listings spread
 *   across 10 zones × 4 types = 40 buckets (≈ 6 listings/bucket), a typical
 *   query finds ~6-15 nearby rows and lands in the 0.4-1.0 confidence band.
 *   This is intentionally conservative: under-populated buckets return
 *   lower confidence, which the UI can surface as "low confidence — fewer
 *   comparable listings in this area".
 */

import { RandomForestRegressor, mulberry32, gaussian } from "./random-forest";
import { buildForestVector, buildSimilarityVector, FOREST_FEATURE_NAMES } from "./preprocessing";
import type { TrainingListing } from "./types";
import type {
  AmenityKey,
  CityZone,
  PricePredictionRequest,
  PricePredictionResponse,
  PropertyType,
} from "./types";

// ─── Domain constants (re-declared so the file is self-contained) ────────────

const TYPES: PropertyType[] = ["SHOP", "HOUSE", "ROOM", "HOSTEL"];
const ZONES: CityZone[] = [
  "Gilgit", "Hunza", "Skardu", "Ghizer", "Ghanche",
  "Shigar", "Kharmang", "Nagar", "Astore", "Diamer",
];
const AMENITY_KEYS: AmenityKey[] = [
  "FURNISHED", "WATER", "ELECTRICITY_BACKUP", "PARKING", "INTERNET",
  "HEATING", "KITCHEN", "ATTACHED_BATH", "SECURITY", "GARDEN",
];

/** City-zone price multipliers (Hunza/Skardu premium due to tourism). */
const ZONE_MULTIPLIER: Record<CityZone, number> = {
  Gilgit: 1.0,
  Hunza: 1.25,
  Skardu: 1.15,
  Ghizer: 0.95,
  Ghanche: 0.9,
  Shigar: 0.9,
  Kharmang: 0.85,
  Nagar: 0.95,
  Astore: 0.9,
  Diamer: 0.85,
};

/** Sample neighbourhoods per zone — purely cosmetic, included as `area`. */
const AREA_BY_ZONE: Record<CityZone, string[]> = {
  Gilgit: ["Jutial", "Konodas", "Sakwar", "Napuri Bazaar"],
  Hunza: ["Karimabad", "Aliabad", "Altit", "Ganish"],
  Skardu: [" Hussain Abad", "Maidan", "Bazaar Road", "New Pango"],
  Ghizer: ["Gahkuch", "Phander", "Punial"],
  Ghanche: ["Khaplu", "Baha"],
  Shigar: ["Shigar Town", "Chutron"],
  Kharmang: ["Kharmang Town", "Mantial"],
  Nagar: ["Nagar Khas", "Minapin", "Hopar"],
  Astore: ["Astore Bazaar", "Rama"],
  Diamer: ["Chilas Town", "Bunji"],
};

// ─── Synthetic dataset generation ───────────────────────────────────────────

/**
 * Generate N synthetic GB rental listings with realistic feature/price
 * distributions (see module header for the exact pricing model).
 *
 * Deterministic: same seed → same dataset → same forest across restarts.
 */
export function generateSyntheticData(
  n = 250,
  seed = 1337,
): TrainingListing[] {
  const rng = mulberry32(seed);
  const listings: TrainingListing[] = [];

  for (let i = 0; i < n; i++) {
    const type = TYPES[Math.floor(rng() * TYPES.length)];
    const cityZone = ZONES[Math.floor(rng() * ZONES.length)];

    // Rooms by type
    let rooms: number;
    let size: number;
    let basePrice: number;
    switch (type) {
      case "SHOP":
        rooms = rng() < 0.7 ? 0 : 1;
        size = 150 + Math.floor(rng() * 600); // 150–750 sqft
        basePrice = 15000 + Math.floor(rng() * 25000); // 15k–40k
        break;
      case "HOUSE":
        rooms = 2 + Math.floor(rng() * 5); // 2–6
        size = 600 + Math.floor(rng() * 2400); // 600–3000 sqft
        basePrice = 30000 + Math.floor(rng() * 90000); // 30k–120k
        break;
      case "ROOM":
        rooms = 1;
        size = 150 + Math.floor(rng() * 450); // 150–600 sqft
        basePrice = 8000 + Math.floor(rng() * 12000); // 8k–20k
        break;
      case "HOSTEL":
        rooms = 1 + Math.floor(rng() * 3); // 1–3 beds
        size = 100 + Math.floor(rng() * 200); // 100–300 sqft/bed
        basePrice = 6000 + Math.floor(rng() * 9000); // 6k–15k per bed
        break;
    }

    // City-zone multiplier
    const cityMult = ZONE_MULTIPLIER[cityZone];
    let subtotal = basePrice * cityMult;

    // Amenities — pick a realistic subset per zone
    const amenities: AmenityKey[] = [];
    const tryAmenity = (key: AmenityKey, prob: number, add: number) => {
      if (rng() < prob) {
        amenities.push(key);
        subtotal += add;
      }
    };

    // WATER & ELECTRICITY_BACKUP are near-universal
    tryAmenity("WATER", 0.92, 2000 + Math.floor(rng() * 1500));
    tryAmenity("ELECTRICITY_BACKUP", 0.7, 3000 + Math.floor(rng() * 2000));

    // FURNISHED & PARKING common in touristy Hunza/Skardu
    const touristy = cityZone === "Hunza" || cityZone === "Skardu";
    tryAmenity("FURNISHED", touristy ? 0.6 : 0.3, 4000 + Math.floor(rng() * 1500));
    tryAmenity("PARKING", touristy ? 0.7 : 0.45, 3000 + Math.floor(rng() * 2000));

    // HEATING common in cold Skardu/Astore
    const cold = cityZone === "Skardu" || cityZone === "Astore" || cityZone === "Hunza";
    tryAmenity("HEATING", cold ? 0.65 : 0.25, 2500 + Math.floor(rng() * 1500));

    // Kitchen / attached bath mainly for rooms & houses
    if (type === "ROOM" || type === "HOUSE" || type === "HOSTEL") {
      tryAmenity("KITCHEN", 0.55, 2500 + Math.floor(rng() * 1500));
      tryAmenity("ATTACHED_BATH", 0.6, 3000 + Math.floor(rng() * 1500));
    }

    // Internet anywhere, more so for rooms/hostels
    tryAmenity("INTERNET", type === "ROOM" || type === "HOSTEL" ? 0.55 : 0.35, 2000 + Math.floor(rng() * 1500));

    // Security & garden are rarer / for higher-end
    if (type === "HOUSE") {
      tryAmenity("SECURITY", 0.4, 3000 + Math.floor(rng() * 2000));
      tryAmenity("GARDEN", 0.35, 3500 + Math.floor(rng() * 1500));
    } else if (type === "SHOP") {
      tryAmenity("SECURITY", 0.3, 3000 + Math.floor(rng() * 2000));
    }

    // Rooms add +8k each (Houses & rooms mainly)
    if (type === "HOUSE" || type === "ROOM") {
      subtotal += rooms * 8000;
    } else if (type === "HOSTEL") {
      subtotal += rooms * 5000; // hostel beds cheaper
    }

    // Size adds ~ PKR 30 / sqft
    subtotal += size * 30;

    // ±10 % Gaussian noise
    const noisy = gaussian(rng, subtotal, subtotal * 0.10);
    let price = Math.max(3000, Math.round(noisy / 500) * 500); // round to nearest 500
    if (price > 250000) price = 250000;

    const areaOptions = AREA_BY_ZONE[cityZone];
    const area = areaOptions[Math.floor(rng() * areaOptions.length)].trim();

    listings.push({
      id: `syn-${String(i + 1).padStart(3, "0")}`,
      type,
      cityZone,
      area,
      price,
      rooms,
      size,
      amenities,
    });
  }

  return listings;
}

// ─── Cached singleton model ─────────────────────────────────────────────────

let _trainingData: TrainingListing[] | null = null;
let _forest: RandomForestRegressor | null = null;
let _forestMatrix: number[][] | null = null; // forest vectors for all training rows
let _simMatrix: number[][] | null = null; // similarity vectors for all training rows
let _simIds: string[] | null = null;

export interface TrainedModels {
  forest: RandomForestRegressor;
  trainingData: TrainingListing[];
  forestMatrix: number[][];
  simMatrix: number[][];
  simIds: string[];
  featureNames: string[];
}

/** Build & cache all models. Safe to call repeatedly — only the first call trains. */
export function trainModels(): TrainedModels {
  if (_forest && _trainingData && _forestMatrix && _simMatrix && _simIds) {
    return {
      forest: _forest,
      trainingData: _trainingData,
      forestMatrix: _forestMatrix,
      simMatrix: _simMatrix,
      simIds: _simIds,
      featureNames: FOREST_FEATURE_NAMES,
    };
  }

  const trainingData = generateSyntheticData(250, 1337);
  const forestMatrix = trainingData.map((r) => buildForestVector(r));
  const y = trainingData.map((r) => r.price);
  const simMatrix = trainingData.map((r) =>
    buildSimilarityVector({
      type: r.type,
      cityZone: r.cityZone,
      rooms: r.rooms,
      size: r.size,
      price: r.price,
      amenities: r.amenities,
    }),
  );
  const simIds = trainingData.map((r) => r.id);

  const forest = new RandomForestRegressor(forestMatrix, y, {
    nTrees: 30,
    maxDepth: 8,
    minSamplesSplit: 4,
    minSamplesLeaf: 2,
    seed: 20240901,
  });

  _trainingData = trainingData;
  _forest = forest;
  _forestMatrix = forestMatrix;
  _simMatrix = simMatrix;
  _simIds = simIds;

  return {
    forest,
    trainingData,
    forestMatrix,
    simMatrix,
    simIds,
    featureNames: FOREST_FEATURE_NAMES,
  };
}

/** Public accessor for the raw training data (used by the /health endpoint). */
export function getTrainingData(): TrainingListing[] {
  if (!_trainingData) trainModels();
  return _trainingData!;
}

// ─── Price prediction + explanation generation ─────────────────────────────

import { cosineSimilarity, topKCosine } from "./knn";

const PKR = (n: number): string => `PKR ${Math.round(n).toLocaleString()}`;

/**
 * Produce a short human description of an amenities subset, e.g.
 *   ["FURNISHED","PARKING"] → "furnished, parking"
 *   []                        → "standard"
 */
function describeAmenities(amenities: AmenityKey[]): string {
  if (amenities.length === 0) return "standard";
  const labels: Record<AmenityKey, string> = {
    FURNISHED: "furnished",
    WATER: "water",
    ELECTRICITY_BACKUP: "electricity backup",
    PARKING: "parking",
    INTERNET: "internet",
    HEATING: "heating",
    KITCHEN: "kitchen",
    ATTACHED_BATH: "attached bath",
    SECURITY: "security",
    GARDEN: "garden",
  };
  const parts = amenities.slice(0, 4).map((a) => labels[a]);
  if (amenities.length > 4) parts.push("more");
  return parts.join(", ");
}

const TYPE_LABEL: Record<PropertyType, string> = {
  SHOP: "shop",
  HOUSE: "house",
  ROOM: "room",
  HOSTEL: "hostel bed",
};

/**
 * Predict price for a listing using the cached forest, plus build the
 * explanation + confidence interval + confidence score.
 *
 * Confidence heuristic — see module header:
 *   nNear = # training rows with cosine-similarity (sim vec incl. predicted
 *           price substituted for the price dim) > 0.85
 *   confidence = clamp(nNear / 15, 0, 1)
 */
export function predictPrice(req: PricePredictionRequest): PricePredictionResponse {
  const { forest, trainingData, simMatrix, simIds, featureNames } = trainModels();

  // Build query forest vector & predict
  const xQuery = buildForestVector(req);
  const predictedPrice = Math.round(forest.predict(xQuery) / 500) * 500;

  // Build query similarity vector — uses predicted price as the price dim,
  // since the request does not carry a price.
  const querySim = buildSimilarityVector({
    type: req.type,
    cityZone: req.cityZone,
    rooms: req.rooms,
    size: req.size,
    price: predictedPrice,
    amenities: req.amenities,
  });

  // Find 5 nearest training rows for the explanation
  const nearest = topKCosine(simMatrix, simIds, querySim, 5);
  const nearestRows = nearest
    .map((m) => trainingData.find((r) => r.id === m.id))
    .filter((r): r is TrainingListing => !!r);
  const avgActual = nearestRows.length
    ? nearestRows.reduce((s, r) => s + r.price, 0) / nearestRows.length
    : predictedPrice;

  // Confidence heuristic: count training rows with cosine sim > 0.85
  let nNear = 0;
  for (const v of simMatrix) {
    if (cosineSimilarity(querySim, v) > 0.85) nNear++;
  }
  const confidence = Math.min(1, nNear / 15);

  // Confidence interval: predicted ±15 %
  const low = Math.round((predictedPrice * 0.85) / 500) * 500;
  const high = Math.round((predictedPrice * 1.15) / 500) * 500;

  // Features echo for the response
  const features: Record<string, number | string> = {};
  for (let f = 0; f < featureNames.length; f++) {
    features[featureNames[f]] = xQuery[f];
  }
  // Also surface the top-3 feature importances so the UI can show "what drove this"
  const importances = forest.featureImportances();
  const ranked = featureNames
    .map((name, idx) => ({ name, importance: importances[idx] ?? 0 }))
    .sort((a, b) => b.importance - a.importance)
    .slice(0, 3);
  features["top_drivers"] = ranked.map((r) => `${r.name}:${r.importance.toFixed(3)}`).join(", ");

  // Explanation template
  const ratio = (predictedPrice - avgActual) / (avgActual || 1);
  let comparison: string;
  if (Math.abs(ratio) < 0.05) comparison = "around";
  else if (ratio > 0) comparison = "above";
  else comparison = "below";

  const amenitiesPhrase = describeAmenities(req.amenities);
  const sizeVal = req.size == null ? "unknown" : `~${req.size}`;
  const zonePhrase = nearestRows[0]?.cityZone ?? req.cityZone;

  const explanation =
    `Based on 5 similar listings in ${zonePhrase} (avg actual ${PKR(avgActual)}), ` +
    `a ${amenitiesPhrase} ${req.rooms}-room ${TYPE_LABEL[req.type]} of ${sizeVal} sqft ` +
    `is fairly priced around ${PKR(predictedPrice)}. ` +
    `Your listing's price is ${comparison} the model's suggestion.`;

  return {
    predictedPrice,
    low,
    high,
    confidence,
    features,
    explanation,
  };
}
